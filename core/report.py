"""Self-contained HTML audit report for one application."""
import base64
import html
from pathlib import Path

from .config import CHECK_LABELS, DECISION_COLORS, UPLOAD_DIR, WEIGHTS
from .scoring import summary_text


def app_image(app_id: str, name: str) -> bytes | None:
    for p in (UPLOAD_DIR / f"{app_id}_{name}.png", UPLOAD_DIR / f"{app_id}_{name}.jpg"):
        if p.exists():
            return p.read_bytes()
    return None


def _img(data: bytes | None, mime="image/png", h=170):
    if not data:
        return "<div class='noimg'>not available</div>"
    return f"<img style='height:{h}px' src='data:{mime};base64,{base64.b64encode(data).decode()}'/>"


def _bar(v):
    col = "#1a7f37" if v <= 30 else "#b58500" if v <= 60 else "#d4561c" if v <= 80 else "#c62828"
    return f"<div class='bar'><div style='width:{v}%;background:{col}'></div></div>"


def build(app: dict, audit: list[dict]) -> str:
    e = html.escape
    res = app["results"]
    s, checks = res["scoring"], res["checks"]
    col = DECISION_COLORS.get(app["decision"], "#555")
    rows = "".join(
        f"<tr><td>{CHECK_LABELS[k]}</td><td>{int(WEIGHTS[k]*100)}%</td><td>{checks[k]['risk']}</td><td>{_bar(checks[k]['risk'])}</td></tr>"
        for k in WEIGHTS if k in checks)
    reasons = "".join(f"<li><b>[{e(r['severity'].upper())}] {e(r['check'])}</b> — {e(r['message'])} <code>{e(r['code'])}</code></li>"
                      for r in s["reasons"]) or "<li>No risk signals.</li>"
    passed = "".join(f"<li>{e(p['check'])}: {e(p['message'])}</li>" for p in s["passed"])
    trail = "".join(f"<tr><td>{e(a['ts'])}</td><td>{e(a['actor'])}</td><td>{e(a['action'])}</td><td>{e(a['note'] or '')}</td></tr>" for a in audit)
    sel = Path(app["selfie_path"]).read_bytes() if app.get("selfie_path") and Path(app["selfie_path"]).exists() else None
    idd = Path(app["id_path"]).read_bytes() if app.get("id_path") and Path(app["id_path"]).exists() else None
    return f"""<!DOCTYPE html><html><head><meta charset='utf-8'><title>KYC Guard report {e(app['id'])}</title>
<style>
body{{font-family:Segoe UI,Arial,sans-serif;max-width:960px;margin:24px auto;color:#1b2430;padding:0 16px}}
h1{{margin:0}} .muted{{color:#6b7684}} .badge{{display:inline-block;padding:8px 16px;border-radius:8px;color:#fff;font-weight:700;background:{col}}}
table{{border-collapse:collapse;width:100%;margin:8px 0}} td,th{{border-bottom:1px solid #e3e8ee;padding:6px 8px;text-align:left;font-size:14px}}
.bar{{background:#eef1f4;height:10px;border-radius:5px;width:220px}} .bar div{{height:10px;border-radius:5px}}
.imgs{{display:flex;gap:16px;flex-wrap:wrap}} .imgs figure{{margin:0}} figcaption{{font-size:12px;color:#6b7684}}
pre{{background:#f6f8fa;padding:12px;border-radius:8px;white-space:pre-wrap}} code{{color:#6b7684;font-size:12px}}
.noimg{{width:140px;height:120px;background:#f0f2f5;display:flex;align-items:center;justify-content:center;color:#999;font-size:12px}}
</style></head><body>
<h1>Identity Verification Report</h1>
<p class='muted'>Application {e(app['id'])} · submitted {e(app['created_at'])} · generated by KYC Guard (hackathon POC)</p>
<p><span class='badge'>{e(app['decision'])}</span> &nbsp; <b style='font-size:22px'>Risk score {app['score']}/100</b>
&nbsp; <span class='muted'>Status: {e(app['status'])}</span></p>
<h2>Decision summary</h2><pre>{e(summary_text(app['id'], s))}</pre>
<h2>Applicant</h2><table>
<tr><td>Name</td><td>{e(app['name'])}</td><td>DOB</td><td>{e(app['dob'])}</td></tr>
<tr><td>ID number</td><td>{e(app['id_masked'] or '')}</td><td>Phone</td><td>{e(app['phone'] or '')}</td></tr>
<tr><td>Device</td><td>{e(app['device_id'] or '')}</td><td>IP</td><td>{e(app['ip'] or '')}</td></tr></table>
<h2>Evidence</h2><div class='imgs'>
<figure>{_img(sel,'image/jpeg')}<figcaption>Selfie</figcaption></figure>
<figure>{_img(idd,'image/jpeg')}<figcaption>ID document</figcaption></figure>
<figure>{_img(app_image(app['id'],'ela'))}<figcaption>Tamper analysis (red = edited after issue)</figcaption></figure>
</div>
<h2>Check scores</h2><table><tr><th>Check</th><th>Weight</th><th>Risk</th><th></th></tr>{rows}</table>
<p class='muted'>Weighted score {s['weighted']} · hard-rule floor {s['floor']}{(' (' + e(s['floor_reason']) + ')') if s['floor_reason'] else ''} · final = max(weighted, floor)</p>
<h2>Risk findings</h2><ul>{reasons}</ul>
<h2>Checks passed</h2><ul>{passed}</ul>
<h2>Audit trail</h2><table><tr><th>Time</th><th>Actor</th><th>Action</th><th>Note</th></tr>{trail}</table>
<p class='muted' style='font-size:12px'>Privacy: full ID numbers are never stored; only a masked value and a keyed hash used for duplicate detection.
Demo documents are fictional SPECIMEN cards.</p>
</body></html>"""
